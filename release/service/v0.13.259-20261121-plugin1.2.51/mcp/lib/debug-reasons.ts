export function debugCode(value: unknown): string | null {
  if (typeof value === "string" && Object.hasOwn(debugReasons, value)) return value;
  if (typeof value === "number" && [-32700, -32600, -32601, -32602, -32603, -32001].includes(value))
    return String(value);
  return value == null ? null : "UNKNOWN_ERROR";
}
